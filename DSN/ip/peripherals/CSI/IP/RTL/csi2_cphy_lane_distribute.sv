//-----------------------------------------------------------------------------
// csi2_cphy_lane_distribute.sv
// CSI-2 byte stream -> C-PHY 16-bit-per-lane words (clk_i domain).
//
// Mapping (spec 8.2.1): byte stream is cut into 16-bit words (byte 0 = [7:0])
// and dealt to the lanes round-robin. One beat carries at most ONE 16-bit
// word per lane, so for N lanes a beat holds up to 2*N bytes:
//     global byte g of the beat -> lane g/2, bits [lane*16 + (g%2)*8 +: 8]
// 2 lanes: beat0 = {L1: B1,B0 ; L0: ...} i.e. bytes 1,0 -> first lane,
//          bytes 3,2 -> second lane, bytes 5,4 -> first lane (next beat)...
//
// Sync Word: when a byte flagged with byte_sync_i is accepted, the current
// data beat is closed and ONE extra beat follows with cphy_sync_o = '1 and
// cphy_keep_o = '1 on every lane. The PPI turns it into TxSendSyncHS; the
// Sync Word itself is generated by the PHY (data of that beat is don't-care).
//
// An odd byte count at packet end is padded with 0x00 (safety net).
//-----------------------------------------------------------------------------
module csi2_cphy_lane_distribute #(
  parameter int NUM_LANES = 2
)(
  input  logic clk_i,
  input  logic rst_ni,

  input  logic       byte_valid_i,
  output logic       byte_ready_o,
  input  logic [7:0] byte_data_i,
  input  logic       byte_sop_i,
  input  logic       byte_eop_i,
  input  logic       byte_sync_i,      // Sync Word follows this byte
  input  logic       tx_active_i,

  output logic       cphy_req_o,
  input  logic       cphy_req_ready_i,
  output logic       cphy_burst_o,

  output logic [NUM_LANES*16-1:0] cphy_data_o,
  output logic [NUM_LANES-1:0]    cphy_valid_o,
  input  logic                    cphy_ready_i,
  output logic [NUM_LANES*2-1:0]  cphy_keep_o,   // per byte
  output logic                    cphy_last_o,
  output logic [NUM_LANES-1:0]    cphy_sync_o    // per lane: this 16-bit word is a Sync Word
);

  initial begin
    if ((NUM_LANES < 1) || (NUM_LANES > 4))
      $error("NUM_LANES must be between 1 and 4");
  end

  localparam int MAX_BYTES = NUM_LANES * 2;
  localparam int COUNT_W   = $clog2(MAX_BYTES + 1);

  logic [7:0]         byte_buf_q [0:MAX_BYTES-1];
  logic [COUNT_W-1:0] byte_count_q;
  logic [COUNT_W-1:0] word_bytes_q;
  logic               word_valid_q;
  logic               word_last_q;
  logic               sync_after_q;   // a sync beat must follow the current data beat
  logic               sync_beat_q;    // current beat IS the sync beat
  logic               cphy_req_granted_q;

  assign cphy_req_o   = tx_active_i && !cphy_req_granted_q;
  assign cphy_burst_o = cphy_req_granted_q;

  wire cphy_req_fire  = cphy_req_o && cphy_req_ready_i;
  wire cphy_word_fire = word_valid_q && cphy_ready_i;

  // No new bytes while a beat is waiting: outputs stay stable under stall.
  assign byte_ready_o = cphy_req_granted_q && !word_valid_q;
  wire   byte_fire    = byte_valid_i && byte_ready_o;

  assign cphy_last_o = word_valid_q && word_last_q && !sync_beat_q;

  //--------------------------------------------------------------------------
  // Output beat
  //--------------------------------------------------------------------------
  always_comb begin
    cphy_data_o  = '0;
    cphy_keep_o  = '0;
    cphy_valid_o = '0;
    cphy_sync_o  = '0;

    // byte g -> lane g/2, byte-in-word g%2 ; keep index = lane*2 + g%2 = g
    for (int g = 0; g < MAX_BYTES; g++) begin
      if (g < int'(word_bytes_q)) begin
        cphy_data_o[(g/2)*16 + (g%2)*8 +: 8] = byte_buf_q[g];
        cphy_keep_o[g]                       = 1'b1;
      end
    end

    // Sync beat: every lane carries one Sync Word (data don't-care)
    if (word_valid_q && sync_beat_q) begin
      cphy_keep_o = '1;
      cphy_sync_o = '1;
    end

    for (int lane = 0; lane < NUM_LANES; lane++)
      cphy_valid_o[lane] = word_valid_q && (|cphy_keep_o[lane*2 +: 2]);
  end

  //--------------------------------------------------------------------------
  // Byte collection / beat sequencing
  //--------------------------------------------------------------------------
  always_ff @(posedge clk_i or negedge rst_ni) begin
    if (!rst_ni) begin
      byte_count_q       <= '0;
      word_bytes_q       <= '0;
      word_valid_q       <= 1'b0;
      word_last_q        <= 1'b0;
      sync_after_q       <= 1'b0;
      sync_beat_q        <= 1'b0;
      cphy_req_granted_q <= 1'b0;
      for (int i = 0; i < MAX_BYTES; i++) byte_buf_q[i] <= 8'h00;
    end else begin

      if (cphy_req_fire) cphy_req_granted_q <= 1'b1;

      if (byte_fire) begin
        byte_buf_q[byte_count_q] <= byte_data_i;

        if (byte_eop_i || byte_sync_i || (byte_count_q == COUNT_W'(MAX_BYTES-1))) begin
          if (byte_eop_i && !byte_count_q[0]) begin
            // odd total byte count: pad one zero byte to finish the 16-bit word
            byte_buf_q[byte_count_q + 1'b1] <= 8'h00;
            word_bytes_q <= byte_count_q + COUNT_W'(2);
          end else begin
            word_bytes_q <= byte_count_q + COUNT_W'(1);
          end
          word_valid_q <= 1'b1;
          word_last_q  <= byte_eop_i;
          sync_after_q <= byte_sync_i && !byte_eop_i;
          byte_count_q <= '0;
        end else begin
          byte_count_q <= byte_count_q + 1'b1;
        end
      end

      // byte_fire and cphy_word_fire are mutually exclusive (byte_ready_o
      // is low while word_valid_q is high), so there is no conflict here.
      if (cphy_word_fire) begin
        word_bytes_q <= '0;
        word_last_q  <= 1'b0;
        byte_count_q <= '0;
        if (sync_after_q) begin
          word_valid_q <= 1'b1;     // issue the sync beat
          sync_beat_q  <= 1'b1;
          sync_after_q <= 1'b0;
        end else begin
          word_valid_q <= 1'b0;
          sync_beat_q  <= 1'b0;
        end
        if (word_last_q) cphy_req_granted_q <= 1'b0;
      end

    end
  end

endmodule
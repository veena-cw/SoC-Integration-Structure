static void start_main(void);

__attribute__((naked, section(".text.start"), used))
void _start(void)
{
  __asm__ volatile (
    DUAL_CORE_STACK_INIT
    "jal ra, start_main\n"
    "1: j 1b\n"
  );
}

static void start_main(void)
{
  uint64_t expected_checksum = 0;
  uint64_t checksum = 0;
  uint64_t fail = 0;

  for (uint64_t i = 0; i < DATA_LINES; i++)
    expected_checksum += (0xD011000000000000ULL | i);

  for (uint64_t round = 0; round < TEST_ROUNDS; round++) {
    for (uint64_t i = 0; i < DATA_LINES; i++) {
      uint64_t value = pressure_data[i];
      checksum += value;
      if (value != (0xD011000000000000ULL | i))
        fail |= 1ULL << (i & 63);
    }
  }

  if (checksum != expected_checksum * TEST_ROUNDS)
    fail |= 1ULL << 32;

  RESULT_ADDR[0] = fail;
  RESULT_ADDR[1] = checksum;
  RESULT_ADDR[2] = expected_checksum;
  RESULT_ADDR[3] = DATA_LINES;
  RESULT_ADDR[4] = TEST_ROUNDS;
  RESULT_ADDR[5] = 0x00000003ULL;
  RESULT_ADDR[6] = 0xC0DE0011ULL;
  RESULT_ADDR[7] = 0x4241434B50524553ULL;
  __asm__ volatile ("fence rw, rw" ::: "memory");

  tohost_exit(fail ? 1 : 0);
}

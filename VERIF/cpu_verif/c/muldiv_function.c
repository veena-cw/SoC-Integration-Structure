/* Run one instruction over its generated table; check numbers base+0.. */
#define DEFINE_RUN_CASES(mnemonic) \
  static void run_cases_##mnemonic(uint64_t base) \
  { \
    for (uint64_t i = 0; i < MULDIV_CASES_PER_OP; i++) { \
      uint64_t result; \
      __asm__ volatile (#mnemonic " %0, %1, %2" \
                        : "=r"(result) \
                        : "r"(cases_##mnemonic[i].lhs), \
                          "r"(cases_##mnemonic[i].rhs)); \
      record_and_check(result, cases_##mnemonic[i].expected, base + i); \
    } \
  }


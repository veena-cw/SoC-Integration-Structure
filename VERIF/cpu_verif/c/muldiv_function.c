/* muldiv_function.c
 * Directed RV64M multiply, divide, and remainder test for BP-DV-006.
 * Covers the RV64 and word-sized M-extension operations plus specified
 * divide-by-zero and signed-overflow behavior.
 *
 * Checks (failure code = (number << 1) | 1):
 *     1- 25  basic operations, divide by zero, signed overflow
 *    26- 48  sign combinations (divisor negative, dividend positive; mulh
 *            with a negative rs2; negative high-part result whose low half
 *            is zero), small/large magnitude corners
 *    64-219  generated cases, 12 per instruction (scripts/gen_muldiv_cases.py)
 *   240-247  writeback contention: a div/rem/mulh result is ready while
 *            independent ALU instructions keep the issue slot busy, so the
 *            long pipe waits in DONE until the late-writeback port frees
 */

#include <stdint.h>

/* The image is larger than the default 12 KiB stack floor allows. */
#define DUAL_CORE_STACK_BASE 0x80010000
__asm__ (".globl __stack_floor\n.set __stack_floor, 0x8000F000");

#include "dual_core.h"

#define MULDIV_RESULTS_ADDR ((volatile uint64_t *)HART_DRAM(0x80020000UL))
#define MULDIV_RESULT_COUNT 256UL
#define CACHE_LINE_BYTES 64UL

static void record_and_check(uint64_t result, uint64_t expected,
                             uint64_t test_number)
{
  MULDIV_RESULTS_ADDR[(test_number - 1) & (MULDIV_RESULT_COUNT - 1)] = result;
  if (result != expected)
    tohost_exit((test_number << 1) | 1);
}

#define CHECK_MULDIV(mnemonic, lhs_value, rhs_value, expected, number) \
  do { \
    uint64_t lhs = (uint64_t)(lhs_value); \
    uint64_t rhs = (uint64_t)(rhs_value); \
    uint64_t result; \
    __asm__ volatile (mnemonic " %0, %1, %2" \
                      : "=r"(result) \
                      : "r"(lhs), "r"(rhs)); \
    record_and_check(result, (uint64_t)(expected), (number)); \
  } while (0)


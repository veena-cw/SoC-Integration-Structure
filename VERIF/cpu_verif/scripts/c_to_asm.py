#!/usr/bin/env python3
"""Turn a C test into readable RISC-V assembly (li, sw, j ...).

  c_to_asm.py c/plic_reg_access.c            -> assembly/plic_reg_access.s
  c_to_asm.py c/foo.c c/bar.c                several files
  c_to_asm.py c/foo.c --opt O0               the code the test image really
                                             uses (RISCV_OPT is -O0; every
                                             variable goes through the stack)

The default is -O1, which is much easier to read than -O0 but is not
instruction-for-instruction the code that runs in simulation. Each C source
line appears as a comment above the instructions it produced. -march comes
from sim/Makefile for that program, so FPU/compressed/bitmanip tests assemble
the same way as in make sim. Compiler bookkeeping (debug sections, .cfi/.loc
directives, internal labels) is removed, and the result is linked as a check
that it is still a complete program.
"""

import argparse
import os
import re
import subprocess
import sys
import tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SIM = os.path.join(ROOT, "sim")
OUT = os.path.join(ROOT, "assembly")
GCC = "riscv64-unknown-elf-gcc"

DROP = re.compile(r"\s*\.(cfi_\w+|loc|file|size|ident|attribute|option\s+nopic)\b")
INTERNAL_LABEL = re.compile(r"\.L(VL|BB|BE|FB|FE|VU|ASF|text|etext|FE|Ltext)\w*:")
SOURCE_COMMENT = re.compile(r"\s*#\s*(\S+\.[ch]):(\d+):\s?(.*)")


def makefile_march(name):
    """RISCV_MARCH the Makefile selects for program `name`."""
    with tempfile.NamedTemporaryFile("w", suffix=".mk") as mk:
        mk.write("pmarch:\n\t@echo $(RISCV_MARCH)\n")
        mk.flush()
        r = subprocess.run(["make", "-s", "-f", "Makefile", "-f", mk.name, "pmarch",
                            f"TCNAME={name}"], cwd=SIM, capture_output=True, text=True)
    words = r.stdout.split()
    return words[-1] if r.returncode == 0 and words else "rv64ima"


def tidy(text):
    """Keep instructions, labels, data and source-line comments."""
    out = []
    for line in text.split("\n"):
        if re.match(r"\s*\.section\s+\.debug", line):
            break                                # debug info runs to the end
        if DROP.match(line) or INTERNAL_LABEL.match(line.strip()):
            continue
        m = SOURCE_COMMENT.match(line)
        if m:
            out.append(f"# {os.path.basename(m.group(1))}:{m.group(2)}: {m.group(3).strip()}")
            continue
        if line.lstrip().startswith("#"):        # other compiler comments
            continue
        out.append(line.split("#", 1)[0].rstrip())   # operand notes after '#'
    keep = [l for l in out if l.strip()]
    return "\n".join(keep) + "\n"


def convert(src, opt):
    name = os.path.splitext(os.path.basename(src))[0]
    march = makefile_march(name)
    dst = os.path.join(OUT, name + ".s")
    os.makedirs(OUT, exist_ok=True)
    with tempfile.TemporaryDirectory() as tmp:
        raw = os.path.join(tmp, name + ".s")
        subprocess.run([GCC, f"-march={march}", "-mabi=lp64", "-mcmodel=medany",
                        "-nostdlib", f"-{opt}", "-g", "-fverbose-asm", "-S",
                        # start_main is static and only called from an asm
                        # block: without this, -O1 deletes the whole test
                        "-fkeep-static-functions",
                        "-I", os.path.dirname(os.path.abspath(src)), src, "-o", raw],
                       check=True)
        with open(raw) as f:
            text = tidy(f.read())
        with open(dst, "w") as f:
            f.write(f"# Generated by scripts/c_to_asm.py from {os.path.basename(src)}\n"
                    f"# -march={march} -{opt}"
                    + ("  (the test image is built with -O0)\n" if opt != "O0" else "\n"))
            f.write(text)
        # the cleaned file must still build into a complete program
        subprocess.run([GCC, f"-march={march}", "-mabi=lp64", "-mcmodel=medany",
                        "-nostdlib", "-T", os.path.join(ROOT, "c", "link.ld"), dst,
                        "-o", os.path.join(tmp, name + ".elf")],
                       check=True, stderr=subprocess.DEVNULL)
    print(f"{src} -> {os.path.relpath(dst, os.getcwd())}  (-march={march} -{opt})")


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("files", nargs="+", help="C source files")
    ap.add_argument("--opt", default="O1", choices=["O0", "O1", "O2", "Os"])
    args = ap.parse_args()
    for src in args.files:
        convert(src, args.opt)


if __name__ == "__main__":
    sys.exit(main())

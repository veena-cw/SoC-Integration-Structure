#!/usr/bin/env python3
"""Generate the operand/expected-result tables used by c/muldiv_function.c
(BP-DV-006). Expected values follow the RISC-V M-extension semantics,
including divide-by-zero and signed-overflow results.

  gen_muldiv_cases.py > tables.inc     (paste between the GENERATED markers)

Fixed seed so the tables are reproducible.
"""

import random

M64 = (1 << 64) - 1
M32 = (1 << 32) - 1
CASES_PER_OP = 12


def s64(x):
    x &= M64
    return x - (1 << 64) if x >> 63 else x


def s32(x):
    x &= M32
    return x - (1 << 32) if x >> 31 else x


def sext32(x):
    return s32(x) & M64


def tdiv(a, b):
    q = abs(a) // abs(b)
    return -q if (a < 0) != (b < 0) else q


def div(a, b, sa, w):
    if w:
        a, b = (s32(a), s32(b)) if sa else (a & M32, b & M32)
        lo = -(1 << 31)
    else:
        a, b = (s64(a), s64(b)) if sa else (a & M64, b & M64)
        lo = -(1 << 63)
    if b == 0:
        q, r = -1, a
    elif sa and a == lo and b == -1:
        q, r = a, 0
    else:
        q = tdiv(a, b)
        r = a - b * q
    if w:
        return sext32(q), sext32(r)
    return q & M64, r & M64


OPS = [
    ("mul",    lambda a, b: (s64(a) * s64(b)) & M64),
    ("mulh",   lambda a, b: ((s64(a) * s64(b)) >> 64) & M64),
    ("mulhsu", lambda a, b: ((s64(a) * (b & M64)) >> 64) & M64),
    ("mulhu",  lambda a, b: (((a & M64) * (b & M64)) >> 64) & M64),
    ("div",    lambda a, b: div(a, b, True, False)[0]),
    ("divu",   lambda a, b: div(a, b, False, False)[0]),
    ("rem",    lambda a, b: div(a, b, True, False)[1]),
    ("remu",   lambda a, b: div(a, b, False, False)[1]),
    ("mulw",   lambda a, b: sext32(s32(a) * s32(b))),
    ("divw",   lambda a, b: div(a, b, True, True)[0]),
    ("divuw",  lambda a, b: div(a, b, False, True)[0]),
    ("remw",   lambda a, b: div(a, b, True, True)[1]),
    ("remuw",  lambda a, b: div(a, b, False, True)[1]),
]

SPECIAL = [0, 1, M64, 1 << 63, (1 << 63) - 1, 2, M64 - 1, 1 << 32,
           M64 ^ M32, 0x80000000, 0x7FFFFFFF, 0xFFFFFFFF80000000, 3, M64 - 2]


def operand(rng):
    r = rng.random()
    if r < 0.30:
        return rng.choice(SPECIAL)
    if r < 0.50:   # small magnitude, either sign
        return rng.randrange(-1000, 1000) & M64
    if r < 0.65:   # 32-bit range values
        return rng.getrandbits(32) | (M64 ^ M32 if rng.random() < 0.5 else 0)
    return rng.getrandbits(64)


def main():
    rng = random.Random(0xB9006)
    print("/* GENERATED by scripts/gen_muldiv_cases.py - do not edit by hand */")
    print(f"#define MULDIV_CASES_PER_OP {CASES_PER_OP}")
    for name, fn in OPS:
        print(f"static const struct muldiv_case cases_{name}[MULDIV_CASES_PER_OP] = {{")
        for _ in range(CASES_PER_OP):
            a, b = operand(rng), operand(rng)
            print(f"  {{0x{a:016X}UL, 0x{b:016X}UL, 0x{fn(a, b):016X}UL}},")
        print("};")


if __name__ == "__main__":
    main()

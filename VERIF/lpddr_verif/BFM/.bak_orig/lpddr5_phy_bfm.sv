`timescale 1ns/1ps

//============================================================================
// LPDDR5C PHY BFM
//
// Controller
//     |
//     | DFI
//     | dfi_cs_n
//     | dfi_cke
//     | dfi_ca[5:0]       -> command
//     | dfi_addr[31:0]    -> address
//     | dfi_wrdata
//     |
//     v
// PHY BFM
//     |
//     | dram_cmd
//     | dram_addr
//     | dram_wrdata
//     |
//     v
// DRAM Model
//
// Read path:
//
// DRAM Model
//     |
//     | dram_rddata
//     | dram_rddata_valid
//     v
// PHY BFM
//     |
//     | dfi_rddata
//     | dfi_rddata_valid
//     v
// Controller
//============================================================================

module lpddr5_phy_bfm #(
    parameter int DATA_WIDTH = 128,
    parameter int ADDR_WIDTH = 32,
    parameter int CA_WIDTH   = 6
)(
    //========================================================================
    // Clock / Reset
    //========================================================================
    input logic dfi_clk,
    input logic dfi_rst_n,

    //========================================================================
    // Controller -> PHY : DFI
    //========================================================================
    input logic                    dfi_cs_n,
    input logic                    dfi_cke,

    // DFI command/address
    input logic [CA_WIDTH-1:0]     dfi_ca,
    input logic [ADDR_WIDTH-1:0]   dfi_addr,

    //========================================================================
    // DFI write data
    //========================================================================
    input logic [DATA_WIDTH-1:0]   dfi_wrdata,
    input logic [DATA_WIDTH/8-1:0] dfi_wrdata_mask,
    input logic                    dfi_wrdata_en,

    //========================================================================
    // PHY -> Controller : Read data
    //========================================================================
    output logic [DATA_WIDTH-1:0]  dfi_rddata,
    output logic                   dfi_rddata_valid,

    //========================================================================
    // PHY initialization
    //========================================================================
    output logic                   dfi_init_complete,

    //========================================================================
    // PHY master training
    //========================================================================
    output logic                   dfi_phymstr_req,
    input  logic                   dfi_phymstr_ack,

    //========================================================================
    // PHY -> DRAM
    //========================================================================
    output logic                   dram_cmd_valid,
    input  logic                   dram_cmd_ready,

    output logic [CA_WIDTH-1:0]    dram_cmd,
    output logic [ADDR_WIDTH-1:0]  dram_addr,

    //========================================================================
    // PHY -> DRAM : Write data
    //========================================================================
    output logic                   dram_wrdata_valid,
    output logic [DATA_WIDTH-1:0]  dram_wrdata,
    output logic [DATA_WIDTH/8-1:0] dram_wrdata_mask,

    //========================================================================
    // DRAM -> PHY : Read data
    //========================================================================
    input logic [DATA_WIDTH-1:0]   dram_rddata,
    input logic                    dram_rddata_valid
);

    //========================================================================
    // Command encoding
    //
    // Must match the encoding generated by lpddr5c_cmd_scheduler.
    //========================================================================

    localparam logic [CA_WIDTH-1:0] CMD_NOP   = 6'h00;
    localparam logic [CA_WIDTH-1:0] CMD_READ  = 6'h01;
    localparam logic [CA_WIDTH-1:0] CMD_WRITE = 6'h02;
    localparam logic [CA_WIDTH-1:0] CMD_ACT   = 6'h03;

    //========================================================================
    // PHY initialization
    //========================================================================

    typedef enum logic [1:0] {
        PHY_RESET,
        PHY_INIT,
        PHY_READY
    } phy_state_t;

    phy_state_t phy_state;

    integer init_counter;

    //========================================================================
    // Training state
    //========================================================================

    typedef enum logic [1:0] {
        TRAIN_IDLE,
        TRAIN_REQUEST,
        TRAIN_WAIT_ACK,
        TRAIN_DONE
    } train_state_t;

    train_state_t train_state;

    //========================================================================
    // PHY initialization FSM
    //========================================================================

    always_ff @(posedge dfi_clk or negedge dfi_rst_n) begin

        if (!dfi_rst_n) begin

            phy_state         <= PHY_RESET;
            init_counter      <= 0;
            dfi_init_complete <= 1'b0;

        end
        else begin

            case (phy_state)

                //============================================================
                // RESET
                //============================================================
                PHY_RESET: begin

                    init_counter      <= 0;
                    dfi_init_complete <= 1'b0;

                    phy_state <= PHY_INIT;

                end

                //============================================================
                // INITIALIZATION
                //============================================================
                PHY_INIT: begin

                    if (init_counter < 20) begin

                        init_counter <= init_counter + 1;

                    end
                    else begin

                        dfi_init_complete <= 1'b1;
                        phy_state          <= PHY_READY;

                        $display(
                            "[PHY] Initialization complete at %0t",
                            $time
                        );

                    end

                end

                //============================================================
                // READY
                //============================================================
                PHY_READY: begin

                    dfi_init_complete <= 1'b1;

                end

                default: begin

                    phy_state <= PHY_RESET;

                end

            endcase

        end

    end

    //========================================================================
    // DFI COMMAND + ADDRESS -> DRAM
    //
    // dfi_ca   : command
    // dfi_addr : AXI/system address passed through scheduler
    //
    // Example:
    //
    //   dfi_ca   = 6'h01
    //   dfi_addr = 32'hC1B80C66
    //
    // becomes:
    //
    //   dram_cmd  = READ
    //   dram_addr = 32'hC1B80C66
    //========================================================================

    always_ff @(posedge dfi_clk or negedge dfi_rst_n) begin

        if (!dfi_rst_n) begin

            dram_cmd_valid <= 1'b0;
            dram_cmd       <= CMD_NOP;
            dram_addr      <= '0;

        end
        else begin

            // Default: one-cycle command pulse
            dram_cmd_valid <= 1'b0;

            if (phy_state == PHY_READY) begin

                //============================================================
                // DFI command is valid when CS is asserted and CKE is high
                //============================================================

              //  if (!dfi_cs_n && dfi_cke) begin

                    //========================================================
                    // Respect DRAM ready
                    //========================================================

                    if (dram_cmd_ready) begin

                       dram_cmd_valid <= 1'b1;
                        dram_cmd       <= dfi_ca;
                        dram_addr      <= dfi_addr;

                        case (dfi_ca)

                            CMD_NOP: begin

                                $display(
                                    "[PHY] NOP CA=%02h ADDR=%08h TIME=%0t",
                                    dfi_ca,
                                    dfi_addr,
                                    $time
                                );

                            end

                            CMD_READ: begin

                                $display(
                                    "[PHY] READ CA=%02h ADDR=%08h TIME=%0t",
                                    dfi_ca,
                                    dfi_addr,
                                    $time
                                );

                            end

                            CMD_WRITE: begin

                                $display(
                                    "[PHY] WRITE CA=%02h ADDR=%08h TIME=%0t",
                                    dfi_ca,
                                    dfi_addr,
                                    $time
                                );

                            end

                            CMD_ACT: begin

                                $display(
                                    "[PHY] ACT CA=%02h ADDR=%08h TIME=%0t",
                                    dfi_ca,
                                    dfi_addr,
                                    $time
                                );

                            end

                            default: begin

                                $display(
                                    "[PHY] UNKNOWN CMD CA=%02h ADDR=%08h TIME=%0t",
                                    dfi_ca,
                                    dfi_addr,
                                    $time
                                );

                            end

                        endcase

                    end

                end

            end

        end

   // end

    //========================================================================
    // WRITE DATA
    //
    // Controller data path -> PHY -> DRAM
    //========================================================================

    always_ff @(posedge dfi_clk or negedge dfi_rst_n) begin

        if (!dfi_rst_n) begin

            dram_wrdata_valid <= 1'b0;
            dram_wrdata       <= '0;
            dram_wrdata_mask  <= '0;

        end
        else begin

            // Default one-cycle pulse
            dram_wrdata_valid <= 1'b0;

            if (
                dfi_wrdata_en &&
                (phy_state == PHY_READY)
            ) begin

                dram_wrdata_valid <= 1'b1;

                dram_wrdata      <= dfi_wrdata;
                dram_wrdata_mask <= dfi_wrdata_mask;

                $display(
                    "[PHY] WRDATA=%032h MASK=%0h TIME=%0t",
                    dfi_wrdata,
                    dfi_wrdata_mask,
                    $time
                );

            end

        end

    end

    //========================================================================
    // DRAM READ DATA -> PHY -> CONTROLLER
    //========================================================================

    always_ff @(posedge dfi_clk or negedge dfi_rst_n) begin

        if (!dfi_rst_n) begin

            dfi_rddata       <= '0;
            dfi_rddata_valid <= 1'b0;

        end
        else begin

            // Default one-cycle pulse
            dfi_rddata_valid <= 1'b0;

            if (dram_rddata_valid) begin

                dfi_rddata       <= dram_rddata;
                dfi_rddata_valid <= 1'b1;

                $display(
                    "[PHY] RDDATA=%032h TIME=%0t",
                    dram_rddata,
                    $time
                );

            end

        end

    end

    //========================================================================
    // PHY MASTER TRAINING HANDSHAKE
    //========================================================================

    always_ff @(posedge dfi_clk or negedge dfi_rst_n) begin

        if (!dfi_rst_n) begin

            train_state     <= TRAIN_IDLE;
            dfi_phymstr_req <= 1'b0;

        end
        else begin

            case (train_state)

                //============================================================
                // IDLE
                //============================================================
                TRAIN_IDLE: begin

                    dfi_phymstr_req <= 1'b0;

                    if (phy_state == PHY_READY)
                        train_state <= TRAIN_REQUEST;

                end

                //============================================================
                // REQUEST
                //============================================================
                TRAIN_REQUEST: begin

                    dfi_phymstr_req <= 1'b1;

                    $display(
                        "[PHY] Training request sent at %0t",
                        $time
                    );

                    train_state <= TRAIN_WAIT_ACK;

                end

                //============================================================
                // WAIT FOR ACK
                //============================================================
                TRAIN_WAIT_ACK: begin

                    dfi_phymstr_req <= 1'b1;

                    if (dfi_phymstr_ack) begin

                        $display(
                            "[PHY] Training ACK received at %0t",
                            $time
                        );

                        dfi_phymstr_req <= 1'b0;
                        train_state      <= TRAIN_DONE;

                    end

                end

                //============================================================
                // DONE
                //============================================================
                TRAIN_DONE: begin

                    dfi_phymstr_req <= 1'b0;

                end

                default: begin

                    train_state     <= TRAIN_IDLE;
                    dfi_phymstr_req <= 1'b0;

                end

            endcase

        end

    end

endmodule

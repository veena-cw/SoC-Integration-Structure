`timescale 1ns/1ps
`include "uvm_macros.svh"
module tpu_tb_top;
  import uvm_pkg::*;
  import tpu_host_pkg::*;
  import tpu_host_tb_pkg::*;

  // clk_tpu 800 MHz, clk_axil 100 MHz, clk_axi 400 MHz (TPU_Host_Interface.pdf, Table 1.1) and rst_n: generated by
  // the clock & reset agent driver (agent/clk_rst_agent)
  clk_rst_if        CLK_RST_vif();
  tpu_host_AXIL_if  AXIL_vif (.clk_axil(CLK_RST_vif.clk_axil));
  tpu_host_AXI_if   AXI_vif  (.clk_axi(CLK_RST_vif.clk_axi));
  tpu_host_irq_if   IRQ_vif  (.clk_axil(CLK_RST_vif.clk_axil));

  assign AXIL_vif.rst_n = CLK_RST_vif.rst_n;
  assign AXI_vif.rst_n  = CLK_RST_vif.rst_n;
  assign IRQ_vif.rst_n  = CLK_RST_vif.rst_n;

  tpu_host_top #(.AXIL_ADDR_W(AXIL_ADDR_W), .UB_DEPTH(UB_DEPTH), .QUEUE_DEPTH(QUEUE_DEPTH),
                 .MAX_BURST(MAX_BURST), .AXI_ID_W(AXI_ID_W)) dut (
    .clk_tpu (CLK_RST_vif.clk_tpu),
    .clk_axil(CLK_RST_vif.clk_axil),
    .clk_axi (CLK_RST_vif.clk_axi),
    .rst_n   (CLK_RST_vif.rst_n),
    .s_axil_awaddr (AXIL_vif.m_axil_awaddr),  .s_axil_awprot(AXIL_vif.m_axil_awprot),
    .s_axil_awvalid(AXIL_vif.m_axil_awvalid), .s_axil_awready(AXIL_vif.m_axil_awready),
    .s_axil_wdata  (AXIL_vif.m_axil_wdata),   .s_axil_wstrb(AXIL_vif.m_axil_wstrb),
    .s_axil_wvalid (AXIL_vif.m_axil_wvalid),  .s_axil_wready(AXIL_vif.m_axil_wready),
    .s_axil_bresp  (AXIL_vif.m_axil_bresp),   .s_axil_bvalid(AXIL_vif.m_axil_bvalid),
    .s_axil_bready (AXIL_vif.m_axil_bready),
    .s_axil_araddr (AXIL_vif.m_axil_araddr),  .s_axil_arprot(AXIL_vif.m_axil_arprot),
    .s_axil_arvalid(AXIL_vif.m_axil_arvalid), .s_axil_arready(AXIL_vif.m_axil_arready),
    .s_axil_rdata  (AXIL_vif.m_axil_rdata),   .s_axil_rresp(AXIL_vif.m_axil_rresp),
    .s_axil_rvalid (AXIL_vif.m_axil_rvalid),  .s_axil_rready(AXIL_vif.m_axil_rready),
    .m_axi_awid(AXI_vif.s_axi_awid),       .m_axi_awaddr(AXI_vif.s_axi_awaddr),   .m_axi_awlen(AXI_vif.s_axi_awlen),
    .m_axi_awsize(AXI_vif.s_axi_awsize),   .m_axi_awburst(AXI_vif.s_axi_awburst), .m_axi_awlock(AXI_vif.s_axi_awlock),
    .m_axi_awcache(AXI_vif.s_axi_awcache), .m_axi_awprot(AXI_vif.s_axi_awprot),   .m_axi_awqos(AXI_vif.s_axi_awqos),
    .m_axi_awvalid(AXI_vif.s_axi_awvalid), .m_axi_awready(AXI_vif.s_axi_awready),
    .m_axi_wdata(AXI_vif.s_axi_wdata),     .m_axi_wstrb(AXI_vif.s_axi_wstrb),     .m_axi_wlast(AXI_vif.s_axi_wlast),
    .m_axi_wvalid(AXI_vif.s_axi_wvalid),   .m_axi_wready(AXI_vif.s_axi_wready),
    .m_axi_bid(AXI_vif.s_axi_bid),         .m_axi_bresp(AXI_vif.s_axi_bresp),     .m_axi_bvalid(AXI_vif.s_axi_bvalid),
    .m_axi_bready(AXI_vif.s_axi_bready),
    .m_axi_arid(AXI_vif.s_axi_arid),       .m_axi_araddr(AXI_vif.s_axi_araddr),   .m_axi_arlen(AXI_vif.s_axi_arlen),
    .m_axi_arsize(AXI_vif.s_axi_arsize),   .m_axi_arburst(AXI_vif.s_axi_arburst), .m_axi_arlock(AXI_vif.s_axi_arlock),
    .m_axi_arcache(AXI_vif.s_axi_arcache), .m_axi_arprot(AXI_vif.s_axi_arprot),   .m_axi_arqos(AXI_vif.s_axi_arqos),
    .m_axi_arvalid(AXI_vif.s_axi_arvalid), .m_axi_arready(AXI_vif.s_axi_arready),
    .m_axi_rid(AXI_vif.s_axi_rid),         .m_axi_rdata(AXI_vif.s_axi_rdata),     .m_axi_rresp(AXI_vif.s_axi_rresp),
    .m_axi_rlast(AXI_vif.s_axi_rlast),     .m_axi_rvalid(AXI_vif.s_axi_rvalid),   .m_axi_rready(AXI_vif.s_axi_rready),
    .irq(IRQ_vif.irq)
  );

  // VCD waveform of the whole hierarchy (testbench interfaces + DUT), written for every run to one fixed
  // file, waves/tpu_tb_top.vcd, so each new simulation overwrites the previous one (sim/waves is created
  // by `make run`).
  //   +NO_WAVES          no waveform
  //   +WAVES_FILE=<path> other file name
  //   +WAVES_DEPTH=<n>   hierarchy depth for $dumpvars (default 0 = all levels)
  initial begin
    string test_name, wave_file;
    int    depth;
    if ($test$plusargs("NO_WAVES") == 0) begin
      if ($value$plusargs("UVM_TESTNAME=%s", test_name) == 0) test_name = "(no UVM_TESTNAME)";
      if ($value$plusargs("WAVES_FILE=%s", wave_file) == 0)   wave_file = "waves/tpu_tb_top.vcd";
      if ($value$plusargs("WAVES_DEPTH=%d", depth) == 0)      depth = 0;
      $display("[tpu_tb_top] VCD waveform of %s: %s (depth %0d, overwritten by the next simulation)", test_name, wave_file, depth);
      $dumpfile(wave_file);
      $dumpvars(depth, tpu_tb_top);
    end
  end

  initial begin
    uvm_resource_db#(virtual tpu_host_AXI_if)::set("*", "vif", AXI_vif);
    uvm_resource_db#(virtual tpu_host_AXIL_if)::set("*", "vif", AXIL_vif);
    uvm_resource_db#(virtual clk_rst_if)::set("*", "vif", CLK_RST_vif);
    uvm_resource_db#(virtual tpu_host_irq_if)::set("*", "vif", IRQ_vif);
    run_test();
  end
endmodule : tpu_tb_top

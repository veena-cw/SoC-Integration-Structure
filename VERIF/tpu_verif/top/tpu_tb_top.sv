//  Description: Testbench top for tpu_host_top. Connects the clock & reset interface (the three
//               clocks at a fixed ratio and rst_n, all driven by the clock & reset agent; CDC itself
//               is not verified in this plan), the AXI4-Lite (CPU side), AXI4 (external memory side)
//               and irq interfaces, and publishes the virtual interfaces through uvm_resource_db.
//               Plusargs: VCD dump to waves/tpu_tb_top.vcd (overwritten by every run); +NO_WAVES, +WAVES_FILE=, +WAVES_DEPTH=.

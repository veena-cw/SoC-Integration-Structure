        t.size  = vif.mon_cb.cfg_arsize_i;
        t.burst = vif.mon_cb.cfg_arburst_i;
        ar_q.push_back(t);
      end

      // ---------------- R handshake -> complete read ----------------
      if (vif.mon_cb.cfg_rvalid_o && vif.mon_cb.cfg_rready_i) begin
        if (ar_q.size() > 0) begin
